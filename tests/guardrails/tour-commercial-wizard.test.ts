import { readFileSync } from "node:fs"
import { resolve } from "node:path"
import { describe, expect, it } from "vitest"

function read(path: string) {
	return readFileSync(resolve(path), "utf8")
}

describe("tour commercial wizard", () => {
	it("separates participant definitions from public discovery categories", () => {
		const participants = read("src/pages/product/[id]/tickets.astro")
		const categories = read("src/pages/product/[id]/categories.astro")
		const presentation = read("src/components/tours/TourPresentationForm.astro")
		const activityPicker = read("src/components/tours/ExperienceActivityPicker.astro")
		const presentationLoader = read("src/lib/tours/loadTourPresentationForm.ts")
		const categoryChoices = read("src/components/tours/TourCategoryChoices.astro")
		const activityEntry = read("src/pages/product/create/activity.astro")
		const activityCards = read("src/components/tours/ExperienceActivityCards.astro")
		expect(participants).toContain(
			'continueFormId={playbook.active ? "ticketsPlaybookForm" : null}'
		)
		expect(participants).toContain("rows.some((row) => row.isActive)")
		expect(participants).toContain('aria-label="Nombre visible de la entrada ${index + 1}"')
		expect(participants).toContain("categoriesHref")
		expect(participants).not.toContain("ProductCategoryLink")
		// Categories live in presentation; /categories is only a compatibility redirect.
		expect(categories).toContain("tourPresentationCanonicalHref")
		expect(categories).toContain("Compatibility entry")
		expect(categories).not.toContain("publicTourCategories")
		expect(categories).not.toContain("ProductCategoryLink")
		expect(presentation).toContain("ExperienceActivityPicker")
		expect(presentation).toContain("TourCategoryChoices")
		expect(activityEntry).toContain("ExperienceActivityCards")
		expect(activityCards).toContain("data-activity-cards")
		expect(activityPicker).toContain('name="primaryActivityCategoryId"')
		expect(activityPicker).toContain("experienceThemeCompatibility")
		expect(activityPicker).toContain("expectedThemeCompatibilityRevision")
		expect(presentation).toContain("experienceThemeCompatibility")
		expect(presentation).toContain("additionalThemeId")
		expect(categoryChoices).toContain('name = "categoryId"')
		expect(categoryChoices).toContain("Temáticas")
		expect(categoryChoices).toContain("Temas adicionales")
		expect(categoryChoices).toContain("permittedIds")
		expect(presentationLoader).toContain("publicTourCategories")
		expect(presentationLoader).toContain("activities:")
		expect(presentationLoader).toContain("families:")
		expect(presentationLoader).toContain('eq(ProductCategory.dataClass, "production")')
		expect(presentationLoader).toContain('row.isActive && row.classificationKind === "legacy"')
		expect(presentationLoader).toContain('classificationKind === "activity"')
		expect(presentationLoader).toContain('assignmentKind === "additional_theme"')
	})

	it("preserves departure drafts and distinguishes templates from dates", () => {
		const editor = read("src/components/tours/TourSlotProfileEditor.astro")
		const page = read("src/pages/product/[id]/departures/new.astro")
		const optionsIndex = read("src/pages/product/[id]/departures/index.astro")
		expect(editor).toContain("fastt:tour-departure-draft:")
		expect(editor).toContain("Tu borrador sigue guardado")
		expect(editor).toMatch(/Compartido\s+\(reserva directa con cupo común\)/)
		expect(editor).toContain("Privado · por solicitud")
		expect(editor).toContain("FieldHelp")
		expect(editor).toContain("suman al mismo cupo")
		expect(editor).toContain("Ayuda sobre modalidad")
		expect(editor.replace(/\/huésped\/gi, "viajero"/, "")).not.toContain("huésped")
		expect(page).toContain("Define el horario habitual, la capacidad, el idioma y la modalidad")
		expect(page).toContain("Después configurarás el precio.")
		expect(page).toContain("Primero crea una opción")
		expect(page).toContain("Necesitas una opción para definir modalidad, horario y capacidad.")
		expect(page).toContain("TourPrerequisiteCard")
		expect(page).not.toMatch(/configurar precios/i)
		expect(page).not.toContain("Empezar configuración")
		expect(optionsIndex).toContain("data-archive-option-dialog")
		expect(optionsIndex).toContain("data-dismiss-session-dialog")
		expect(optionsIndex).toContain("Archivar opción")
	})
})
